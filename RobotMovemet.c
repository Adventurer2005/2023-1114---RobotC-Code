/*Move forward function*/
void forward(int t)
{
	motor[port2] = 127;
	motor[port3] = 127;
	wait1Msec(t);
}
/*Turn right function*/
void turn_right(int t)
{
	motor[port2] = 127;
	motor[port3] = -127;
	wait1Msec(t);
}
/*Turn left function*/
void turn_left(int t)
{
	motor[port2] = -127;
	motor[port3] = 127;
	wait1Msec(t);
}
/*Push button function*/
void push()
{
	motor[port2] = 0;
	motor[port3] = 0;
	motor[port6] = 127;
	wait1Msec(1000);
	motor[port6] = 127;
}
